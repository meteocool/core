/**
 * Everywhere there is *no* radar: the world, with the covered area cut out.
 *
 * The dark wash the map draws over unsupported regions is this polygon's fill,
 * so the hole is the claim "there is radar here" and the fill is "there is
 * not". It holds every network: what each one's antennas actually reach, not
 * the rectangles their grids are stored on.
 *
 * DWD's part is its published outline, which measures as a union of 150 km
 * circles around its seventeen sites. MeteoSwiss's is 246 km circles around
 * its five, Meteo-France's 256 km around its twenty-four, CHMI's 260 km
 * around its two, IMGW's 250 km around its ten and SHMÚ's 240 km around its
 * four. RMI's differ by site: 200 km round Helchteren, 250 round Jabbeke and
 * Wideumont; so do Met Éireann's, 250 round Dublin and 248.5 round Shannon.
 * The rest run 238 km (DMI) to 250 (KNMI, FMI), `radarSites.ts` has each.
 * Each is the range the network's own files carry as `nbins * rscale` on
 * their lowest tilt (ng's `openradar.reach_m`), read no further than 250 km.
 *
 * The networks are merged into one hole per part instead of one hole each.
 * The shapes overlap, and overlapping interior rings do not punch several
 * holes: under the nonzero winding rule the overlap counts back to filled,
 * so exactly the ground covered twice would have been shaded as having none.
 * Parts that touch nowhere are a hole each, which is safe, as they do not
 * overlap: the continent, and Ireland, whose radars reach no other
 * network's (Dublin is 679 km from Jabbeke, and the middle of Britain is no
 * network's). Inside the continent four islands no radar reaches though
 * radars ring them are rings of their own, which count back to filled for
 * the same reason: the Niedere Tauern, the northern Apennines, the Baltic
 * between Gotland, Latvia and Estonia, and the fells west of Arjeplog.
 *
 * Generated from ng's `coverage.everywhere_reached()` by
 * `scripts/radar-wash.py`, which draws the circles the way ng's coverage
 * document does and simplifies to 200 m, far under a pixel at the zooms this
 * is drawn at. Run it again when a network or a site's reach changes.
 */
export const radarCoverageInv = fromExtent(
  transformExtent([-180, -90, 180, 90], "EPSG:4326", "EPSG:3857"),
);
